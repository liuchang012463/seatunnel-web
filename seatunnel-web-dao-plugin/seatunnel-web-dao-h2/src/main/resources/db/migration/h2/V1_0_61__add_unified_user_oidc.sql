CREATE TABLE t_seatunnel_web_unified_auth_config
(
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    config_key                  VARCHAR(32)  NOT NULL UNIQUE,
    issuer                      VARCHAR(512),
    client_id                   VARCHAR(255),
    redirect_uri                VARCHAR(1024) NOT NULL,
    client_secret_enc           TEXT,
    enabled                     BOOLEAN      NOT NULL DEFAULT FALSE,
    auto_provision_general_user BOOLEAN      NOT NULL DEFAULT FALSE,
    ticket_enabled              BOOLEAN      NOT NULL DEFAULT FALSE,
    ticket_validation_endpoint  VARCHAR(1024),
    ticket_validation_method    VARCHAR(16),
    ticket_login_entry_url      VARCHAR(1024),
    ticket_issuer                VARCHAR(512),
    ticket_parameter_name        VARCHAR(64) NOT NULL DEFAULT 'ticket',
    ticket_success_field         VARCHAR(128),
    ticket_success_value         VARCHAR(255),
    ticket_username_field        VARCHAR(128),
    ticket_result_issuer_pointer VARCHAR(256),
    ticket_result_subject_pointer VARCHAR(256),
    ticket_result_email_pointer VARCHAR(256),
    ticket_result_display_name_pointer VARCHAR(256),
    config_version              BIGINT       NOT NULL DEFAULT 1,
    create_time                 TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time                 TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE t_seatunnel_web_unified_auth_identity
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    identity_key CHAR(64)     NOT NULL UNIQUE,
    identity_source VARCHAR(16) NOT NULL DEFAULT 'OIDC',
    issuer       VARCHAR(512) NOT NULL,
    subject      VARCHAR(255) NOT NULL,
    email        VARCHAR(255),
    display_name VARCHAR(255),
    user_id      INT,
    create_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_unified_auth_identity_user_id
    ON t_seatunnel_web_unified_auth_identity (user_id);
